package main

import (
	"fmt"
	"strings"
)

// panelHeader writes src/<Slug>Panel.hpp: the positions the module widget
// places its parts at, so the widget and the SVG come from one description.
func panelHeader(m *Module) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by tools/panelgen from panels/%s.json. Edit that file and run make panels.\n", m.Slug)
	b.WriteString("#pragma once\n#include <rack.hpp>\n\n")
	fmt.Fprintf(&b, "namespace %sPanel {\n\n", m.Slug)

	placed := m.place()
	var vecs, others strings.Builder
	for _, p := range placed {
		switch {
		case p.Kind == Readout:
			w := m.well(p)
			fmt.Fprintf(&others, "static const rack::math::Rect %s_WELL = %s;\n", p.ID, rect(w))
			fmt.Fprintf(&others, "// %s: centre of each cell's value baseline (px), and the value the module browser shows.\n", p.ID)
			fmt.Fprintf(&others, "static const float %s_VALUE_SIZE = %sf;\n", p.ID, fnum(cellValueSize))
			fmt.Fprintf(&others, "static const rack::math::Vec %s[] = {\n", p.ID)
			for _, c := range p.Cells {
				fmt.Fprintf(&others, "\track::math::Vec(%sf, %sf),\n", fnum(m.colX(c.Col)), fnum(w.Y+cellValueBase))
			}
			others.WriteString("};\n")
			for _, c := range p.Cells {
				if c.Label == "" {
					fmt.Fprintf(&others, "// Cells with no name in the panel have it drawn live, on this baseline.\n")
					fmt.Fprintf(&others, "static const float %s_NAME_BASELINE = %sf;\n", p.ID, fnum(w.Y+cellNameBase))
					break
				}
			}
			fmt.Fprintf(&others, "static const char* const %s_SAMPLE[] = {\n", p.ID)
			for _, c := range p.Cells {
				fmt.Fprintf(&others, "\t%q,\n", c.Sample)
			}
			others.WriteString("};\n\n")
		case isDisplay(p.Kind):
			w := m.well(p)
			fmt.Fprintf(&others, "static const rack::math::Rect %s_WELL = %s;\n", p.ID, rect(w))
			fmt.Fprintf(&others, "static const rack::math::Rect %s[] = {\n", p.ID)
			for _, l := range m.lights(p) {
				fmt.Fprintf(&others, "\t%s,\n", rect(l))
			}
			others.WriteString("};\n\n")
		case p.Kind == ButtonGrid:
			fmt.Fprintf(&others, "static const rack::math::Vec %s[] = {\n", p.ID)
			for _, pt := range m.gridPoints(p) {
				fmt.Fprintf(&others, "\track::math::Vec(%sf, %sf),\n", fnum(pt.X), fnum(pt.Y))
			}
			others.WriteString("};\n\n")
		default:
			fmt.Fprintf(&vecs, "static const rack::math::Vec %s = rack::math::Vec(%sf, %sf);\n", p.ID, fnum(p.X), fnum(p.Y))
		}
	}
	if vecs.Len() > 0 {
		b.WriteString("// Centres of the controls, in px.\n")
		b.WriteString(vecs.String() + "\n")
	}
	if others.Len() > 0 {
		b.WriteString("// Square parts. A button's light is FLAT_LIGHT_SIZE wide, centred on the button;\n")
		b.WriteString("// a display is its well and the boxes of its lights (bars left to right;\n")
		b.WriteString("// keyboard from C to B), in px. A button grid lists centres row by row.\n")
		fmt.Fprintf(&b, "static const float BUTTON_SIZE = %sf;\n", fnum(buttonSize))
		fmt.Fprintf(&b, "static const float FLAT_LIGHT_SIZE = %sf;\n\n", fnum(flatLightSize))
		b.WriteString(others.String())
	}

	b.WriteString("// Top-left corners of the screws, in px.\n")
	b.WriteString("static const rack::math::Vec SCREWS[] = {\n")
	for _, s := range m.screws() {
		fmt.Fprintf(&b, "\track::math::Vec(%sf, %sf),\n", fnum(s[0]), fnum(s[1]))
	}
	b.WriteString("};\n\n")
	fmt.Fprintf(&b, "} // namespace %sPanel\n", m.Slug)
	return b.String()
}

// fnum writes a float literal body that always has a decimal point.
func fnum(v float64) string {
	s := num(v)
	if !strings.Contains(s, ".") {
		s += ".0"
	}
	return s
}

func rect(b Box) string {
	return fmt.Sprintf("rack::math::Rect(rack::math::Vec(%sf, %sf), rack::math::Vec(%sf, %sf))", fnum(b.X), fnum(b.Y), fnum(b.W), fnum(b.H))
}
