// Faces holds the two weights panels use.
type Faces struct {
	SemiBold, Bold *Face
}

// The W72 mark, from the W72 web design system: two W strokes in the panel's
// mark grey and the 7's two cyans, which never change.
var markShapes = []struct {
	fill string
	pts  [][2]float64
}{
	{colMark, [][2]float64{{675.207, 1732}, {184.469, 505.154}, {144.469, 505.154}, {127.89, 463.707}, {675.207, 463.707}, {928.866, 1097.854}}},
	{colMark, [][2]float64{{1341.061, 1732}, {850.323, 505.154}, {810.323, 505.154}, {793.744, 463.707}, {1341.061, 463.707}, {1594.72, 1097.854}}},
	{"#22d3ee", [][2]float64{{1457.152, 505.154}, {1440.573, 463.707}, {1708.378, 463.707}, {1594.476, 748.463}, {1497.152, 505.154}}},
	{"#0891a8", [][2]float64{{1629.476, 835.963}, {1778.378, 463.707}, {1848.378, 463.707}, {1664.476, 923.463}}},
}

const (
	markX0, markY0 = 127.89, 463.707
	markW, markH   = 1720.488, 1268.293
)

// num writes a length with at most three decimals, which is 1 µm in mm.
func num(v float64) string {
	s := strconv.FormatFloat(v, 'f', 3, 64)
	s = strings.TrimRight(s, "0")
	s = strings.TrimSuffix(s, ".")
	if s == "-0" {
		return "0"
	}
	return s
}

func mm(px float64) string { return num(px * mmPerPx) }

type svgWriter struct {
	b strings.Builder
}

func (w *svgWriter) line(format string, args ...any) {
	w.b.WriteString("  ")
	fmt.Fprintf(&w.b, format, args...)
	w.b.WriteString("\n")
}

func (w *svgWriter) rect(id string, x, y, width, height, r float64, fill string) {
	round := ""
	if r > 0 {
		round = fmt.Sprintf(` rx="%s" ry="%s"`, mm(r), mm(r))
	}
	w.line(`<rect id="%s" x="%s" y="%s" width="%s" height="%s"%s fill="%s"/>`,
		id, mm(x), mm(y), mm(width), mm(height), round, fill)
}

// well draws a display's well or a button's bezel: a dark box with a hairline.
func (w *svgWriter) well(id string, b Box) {
	// The stroke is centred on the edge, so the box is pulled in by half of it.
	const hair = 1.0
	w.line(`<rect id="%s" x="%s" y="%s" width="%s" height="%s" rx="%s" ry="%s" fill="%s" stroke="%s" stroke-width="%s"/>`,
		id, mm(b.X+hair/2), mm(b.Y+hair/2), mm(b.W-hair), mm(b.H-hair), mm(wellRadius), mm(wellRadius), colWell, colWellEdge, mm(hair))
}

// text writes a string's paths: one path, or a group when the string needs
// several (see shapes).
func (w *svgWriter) text(id string, ds []string, fill string) {
	if len(ds) == 1 {
		w.line(`<path id="%s" fill="%s" d="%s"/>`, id, fill, ds[0])
		return
	}
	w.line(`<g id="%s">`, id)
	for _, d := range ds {
		w.line(`  <path fill="%s" d="%s"/>`, fill, d)
	}
	w.line(`</g>`)
}

// panelSVG draws the panel: ground, band and title, labels, plate, mark.
// Knobs, jacks, lights and screws are widgets Rack draws on top.
func panelSVG(m *Module, faces Faces) (string, error) {
	W := m.width()
	placed := m.place()
	var w svgWriter

	w.b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>` + "\n")
	fmt.Fprintf(&w.b, "<!-- Generated by tools/panelgen from panels/%s.json. Edit that file and run make panels. -->\n", m.Slug)
	// Height is 128.5 mm by Rack convention; the grid itself is 380 px.
	fmt.Fprintf(&w.b, `<svg xmlns="http://www.w3.org/2000/svg" width="%smm" height="128.5mm" viewBox="0 0 %s 128.5">`+"\n", mm(W), mm(W))

	w.rect("ground", 0, 0, W, panelHeightMM/mmPerPx, 0, colGround)

	// Band and module name, the capitals centred in the band.
	w.rect("band", 0, bandY, W, bandH, 0, families[m.Family])
	size := titleSize
	if m.HP <= 4 {
		size = titleSizeSmall
	}
	title := Text{faces.Bold, size, 0, m.Name}
	d, err := title.PathCentered(W/2, bandY+bandH/2+title.CapHeight()/2)
	if err != nil {
		return "", err
	}
	w.text("title", d, colTitle)

	// Output plate, behind the output labels, with a rule between the groups of
	// outputs the description separates.
	if span, ok := plateSpan(m, placed); ok {
		w.rect("plate", span[0], plateTop, span[1]-span[0], plateBottom-plateTop, plateRadius, colPlate)
	}
	var outs []Placed
	for _, p := range placed {
		if p.Kind == Output && p.Row == 0 {
			outs = append(outs, p)
		}
	}
	for _, id := range m.PlateRules {
		i := m.outputIndex(id)
		x := (outs[i].X + outs[i+1].X) / 2
		for _, s := range m.sections()[1:] {
			if s[0] > outs[i].X && s[0] < outs[i+1].X {
				x = s[0]
			}
		}
		w.rect("rule-"+id, x-ruleWidth/2, plateTop+plateRuleInset, ruleWidth, plateBottom-plateTop-2*plateRuleInset, 0, colPlateRule)
	}

	// Plates higher up: outputs above row 0 get a plate of their own, as tall as
	// the bottom one around them and across their section.
	for i, b := range upperPlates(m, placed) {
		w.rect(fmt.Sprintf("plate-%d", i+1), b.X, b.Y, b.W, b.H, plateRadius, colPlate)
	}

	// Dividers between groups of rows: hairlines midway below the rows they name.
	for _, row := range m.Dividers {
		y := rowY(row) + rowPitch/2
		w.rect(fmt.Sprintf("divider-%d", row), dividerInset, y-ruleWidth/2, W-2*dividerInset, ruleWidth, 0, colDivider)
	}

	// Splits between sections: hairlines down the panel, from under the band to
	// above the plate, as far in as a divider is from the sides.
	for i, s := range m.sections()[1:] {
		top, bottom := bandY+bandH+dividerInset, plateTop-dividerInset
		w.rect(fmt.Sprintf("split-%d", i), s[0]-ruleWidth/2, top, ruleWidth, bottom-top, 0, colDivider)
	}

	// Wells and bezels, under their labels.
	for _, p := range placed {
		for i, b := range m.bezels(p) {
			id := "well-" + p.ID
			if p.Kind == ButtonGrid {
				id = fmt.Sprintf("%s-%d", id, i)
			}
			w.well(id, b)
		}
	}

	// Readout cells: each one's small name under its value; a rule between
	// the groups the description separates.
	for _, p := range placed {
		if p.Kind != Readout {
			continue
		}
		wb := m.well(p)
		for _, cell := range p.Cells {
			// An empty name is drawn live by the widget (Gibigiana's lane number).
			if cell.Label == "" {
				continue
			}
			t := Text{faces.SemiBold, labelSize, labelTracking, strings.ToUpper(cell.Label)}
			d, err := t.PathCentered(m.colX(cell.Col), wb.Y+cellNameBase)
			if err != nil {
				return "", err
			}
			w.text(fmt.Sprintf("label-%s-%d", p.ID, cell.Col), d, colLabel)
		}
		for _, r := range p.Rules {
			x := (m.colX(r) + m.colX(r+1)) / 2
			w.line(`<rect id="rule-%s-%d" x="%s" y="%s" width="%s" height="%s" fill="%s"/>`,
				p.ID, r, mm(x-0.5), mm(wb.Y+cellRuleTop), mm(1), mm(cellRuleEnd-cellRuleTop), colWellEdge)
		}
	}

	// A switch's positions: left of it, above it, right of it, the outer two
	// centred on its height.
	for _, p := range placed {
		if p.Kind != Switch {
			continue
		}
		for i, name := range p.Positions {
			t := Text{faces.SemiBold, labelSize, labelTracking, strings.ToUpper(name)}
			tw, err := t.Width()
			if err != nil {
				return "", err
			}
			mid := p.Y + t.CapHeight()/2
			var d []string
			switch i {
			case 0:
				d, err = t.Path(p.X-switchW/2-labelGap-tw, mid)
			case 1:
				d, err = t.PathCentered(p.X, p.Y-switchH/2-labelGap)
			case 2:
				d, err = t.Path(p.X+switchW/2+labelGap, mid)
			}
			if err != nil {
				return "", err
			}
			w.text(fmt.Sprintf("label-%s-%d", p.ID, i), d, colLabel)
		}
	}

	// Labels: above what they name, below a light or a button, inside a display's well.
	for _, p := range placed {
		if p.Label == "" {
			continue
		}
		face, fill := faces.SemiBold, colLabel
		if p.Kind == Output {
			face, fill = faces.Bold, colPlateLabel
		}
		t := Text{face, labelSize, labelTracking, strings.ToUpper(p.Label)}
		r := radiusPx(p.Kind)
		baseline := p.Y - r - labelGap
		switch {
		case p.Kind == Light:
			baseline = p.Y + r + labelGap + t.CapHeight()
		case p.Kind == Button:
			baseline = p.Y + buttonSize/2 + labelGap + t.CapHeight()
		case isDisplay(p.Kind):
			baseline = m.well(p).Y + wellHeight - wellLabelPad
		}
		d, err := t.PathCentered(p.X, baseline)
		if err != nil {
			return "", err
		}
		w.text("label-"+p.ID, d, fill)
	}

	// The mark: between the bottom screws from 6 HP, above the single screw below,
	// and none on an unsigned panel.
	if !m.signed() {
		w.b.WriteString("</svg>\n")
		return w.b.String(), nil
	}
	mw, cx, cy := 15.0, W/2, screwRowY+screwSize/2
	if m.HP < smallPanel {
		mw = 22
		cy = 361 - mw*markH/markW/2
	}
	s := mw / markW
	mh := markH * s
	w.line(`<g id="mark">`)
	for _, sh := range markShapes {
		var b strings.Builder
		for i, p := range sh.pts {
			if i == 0 {
				b.WriteString("M")
			} else {
				b.WriteString("L")
			}
			b.WriteString(mm(cx-mw/2+(p[0]-markX0)*s) + " " + mm(cy-mh/2+(p[1]-markY0)*s))
		}
		b.WriteString("Z")
		w.line(`  <path fill="%s" d="%s"/>`, sh.fill, b.String())
	}
	w.line(`</g>`)

	w.b.WriteString("</svg>\n")
	return w.b.String(), nil
}

// plateSpan is the plate's left and right edge in px: the columns of the
// outputs in row 0, kept at least plateMargin in from the panel edge.
func plateSpan(m *Module, placed []Placed) ([2]float64, bool) {
	n := 0
	for _, p := range placed {
		if p.Row == 0 {
			n++
		}
	}
	if m.Columns != nil {
		for _, p := range placed {
			if p.Kind == Output && p.Row == 0 {
				return [2]float64{plateMargin, m.width() - plateMargin}, true
			}
		}
		return [2]float64{}, false
	}
	lo, hi, ok := 0.0, 0.0, false
	col := m.width() / float64(max(n, 1))
	for _, p := range placed {
		if p.Kind != Output || p.Row != 0 {
			continue
		}
		l, r := p.X-col/2, p.X+col/2
		if !ok || l < lo {
			lo = l
		}
		if !ok || r > hi {
			hi = r
		}
		ok = true
	}
	return [2]float64{max(lo, plateMargin), min(hi, m.width()-plateMargin)}, ok
}

// upperPlates are the plates of outputs above row 0, one per height and
// section, plateMargin in from the section's edges.
func upperPlates(m *Module, placed []Placed) []Box {
	type key struct {
		y   float64
		sec int
	}
	var out []Box
	seen := map[key]bool{}
	for _, p := range placed {
		if p.Kind != Output || p.Row == 0 {
			continue
		}
		k := key{p.Y, m.sectionOf(p.Control)}
		if seen[k] {
			continue
		}
		seen[k] = true
		s := m.sections()[k.sec]
		out = append(out, Box{s[0] + plateMargin, p.Y - (outputRowY - plateTop), s[1] - s[0] - 2*plateMargin, plateBottom - plateTop})
	}
	return out
}
